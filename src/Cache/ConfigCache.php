<?php

declare(strict_types=1);

namespace Webware\ConfigManager\Cache;

use Brick\VarExporter\VarExporter;
use Throwable;
use Webware\ConfigManager\Exception;
use Webware\ConfigManager\Shape;
use Webware\FileWriter\Exception\ExceptionInterface as FileWriterException;
use Webware\FileWriter\FileWriter;

use function chmod;
use function date;
use function file_exists;
use function is_int;
use function restore_error_handler;
use function set_error_handler;
use function sprintf;

use const PHP_OS_FAMILY;

/**
 * Reads and writes the merged configuration cache.
 *
 * The semantics are the ones Laminas\ConfigAggregator\ConfigAggregator established, and
 * they are reproduced rather than tidied, because an application moving here has to
 * behave the same way:
 *
 * - the cache is READ whenever the file exists, with no regard for
 *   {@see self::ENABLE_CACHE}. Disabling the setting prevents writing, it does not
 *   prevent reading;
 * - the cache is WRITTEN only when the merged configuration sets
 *   {@see self::ENABLE_CACHE} to a truthy value;
 * - a failure to write is swallowed, because a cache that cannot be written costs
 *   performance, not correctness, and must not take the application down.
 *
 * The practical consequence of the first rule is that disabling the cache does nothing
 * while a cache file exists. The file has to be deleted, which is what development mode
 * does.
 *
 * @api
 */
final class ConfigCache
{
    /** Truthy in the merged config to allow the cache to be written. */
    public const string ENABLE_CACHE = 'config_cache_enabled';

    /** Optional file mode applied to the cache file. */
    public const string CACHE_FILEMODE = 'config_cache_filemode';

    /** @param null|string $path Cache file path, or null to disable the cache entirely. */
    public function __construct(
        private readonly ?string $path,
    ) {}

    /**
     * Apply an explicitly configured file mode.
     *
     * FileWriter preserves the mode of a file it replaces and derives one from umask for
     * a new file, so an explicit mode is the only case it cannot honour on its own.
     *
     * @param mixed $mode Whatever the configuration held; only an integer is applied.
     */
    private static function applyMode(string $path, mixed $mode): void
    {
        if (! is_int($mode) || 'Windows' === PHP_OS_FAMILY) {
            return;
        }

        set_error_handler(static fn(): bool => true);

        try {
            chmod($path, $mode);
        } finally {
            restore_error_handler();
        }
    }

    /**
     * Report whether the merged configuration allows the cache to be written.
     *
     * The setting must be the boolean `true`. The aggregator used `empty()`, so `1` or
     * `'yes'` also enabled it; that looseness is dropped deliberately, because a
     * mis-typed setting silently changing whether configuration is cached is worse than
     * reporting it by simply not caching. `no-empty` also forbids the construct.
     *
     * @param array<array-key, mixed> $config
     */
    private static function isEnabled(array $config): bool
    {
        return true === ($config[self::ENABLE_CACHE] ?? false);
    }

    /**
     * Return the cached configuration, or null when there is nothing to read.
     *
     * @return null|array<array-key, mixed>
     * @throws Exception\InvalidArgumentException If the cache file does not return an array.
     */
    public function load(): ?array
    {
        if (null === $this->path || ! file_exists($this->path)) {
            return null;
        }

        // Passed straight into the check so the untyped return of an included file never
        // reaches a variable.
        return Shape::array(
            require $this->path,
            sprintf('Config cache file "%s"', $this->path),
        );
    }

    /**
     * Write the configuration to the cache file, when the configuration allows it.
     *
     * @param array<array-key, mixed> $config
     * @throws Exception\RuntimeException If the configuration cannot be exported.
     */
    public function save(array $config): void
    {
        if (null === $this->path || ! self::isEnabled($config)) {
            return;
        }

        try {
            $contents = sprintf(
                "<?php\n\n// Generated by %s at %s.\n// Delete this file to rebuild it.\n\nreturn %s;\n",
                self::class,
                date('c'),
                VarExporter::export($config, VarExporter::CLOSURE_SNAPSHOT_USES),
            );
        } catch (Throwable $throwable) {
            throw new Exception\RuntimeException(
                sprintf('Unable to export the configuration cache: %s', $throwable->getMessage()),
                0,
                $throwable,
            );
        }

        try {
            FileWriter::write($this->path, $contents);
        } catch (FileWriterException) {
            // Parity with the aggregator: an unwritable cache is a performance problem,
            // not a correctness one, so the application keeps running without it.
            return;
        }

        self::applyMode($this->path, $config[self::CACHE_FILEMODE] ?? null);
    }
}
